import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { compareStrings, isRecord, type CheckResult } from './common.js';
import type { CopiedEntry } from './copied-code.js';
import { sortCopied } from './copied-code.js';
import type { LeveledPackage } from './pnpm.js';

export interface NoticeFile {
  fileName: string;
  text: string;
}

export interface NoticePackage {
  name: string;
  version: string;
  license: string;
  /** From the package's own package.json; where to get the source of MPL-2.0 packages. */
  repository: string | undefined;
  licenseFiles: NoticeFile[];
  /** Apache-2.0 packages only: the NOTICE file, when it exists. */
  noticeFile: NoticeFile | undefined;
}

const LICENSE_FILE = /^(licen[cs]e|copying)([-._].*)?$/i;
const NOTICE_FILE = /^notice([-._].*)?$/i;

function normalizeText(text: string): string {
  return text
    .replace(/^\uFEFF/, '')
    .replace(/\r\n?/g, '\n')
    .split('\n')
    .map((line) => line.trimEnd())
    .join('\n')
    .trim();
}

function normalizeRepository(raw: string): string {
  let url = raw.trim().replace(/^git\+/, '');
  if (/^[\w.-]+\/[\w.-]+$/.test(url)) url = `github:${url}`;
  const shorthand = /^(github|gitlab|bitbucket):(.+)$/.exec(url);
  if (shorthand?.[1] !== undefined && shorthand[2] !== undefined) {
    url = `https://${shorthand[1]}.${shorthand[1] === 'bitbucket' ? 'org' : 'com'}/${shorthand[2]}`;
  }
  return url
    .replace(/^git:\/\//, 'https://')
    .replace(/^ssh:\/\/git@/, 'https://')
    .replace(/\.git$/, '');
}

function readRepository(packageDir: string): string | undefined {
  try {
    const json: unknown = JSON.parse(readFileSync(path.join(packageDir, 'package.json'), 'utf8'));
    if (!isRecord(json)) return undefined;
    const repo = json.repository;
    if (typeof repo === 'string') return normalizeRepository(repo);
    if (isRecord(repo) && typeof repo.url === 'string') return normalizeRepository(repo.url);
    return undefined;
  } catch {
    return undefined;
  }
}

export function isApache(license: string): boolean {
  return /apache-2\.0/i.test(license);
}

export function isMpl(license: string): boolean {
  return /mpl-2\.0/i.test(license);
}

function readMatching(dir: string, pattern: RegExp): NoticeFile[] {
  const names = readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && pattern.test(entry.name))
    .map((entry) => entry.name)
    .sort(compareStrings);
  return names.map((fileName) => ({
    fileName,
    text: normalizeText(readFileSync(path.join(dir, fileName), 'utf8')),
  }));
}

/** Reads LICENSE/NOTICE files from the installed packages (level B only). */
export function gatherNoticePackages(packages: readonly LeveledPackage[]): NoticePackage[] {
  return packages
    .filter((pkg) => pkg.level === 'B')
    .map((pkg) => ({
      name: pkg.name,
      version: pkg.version,
      license: pkg.license,
      repository: readRepository(pkg.path),
      licenseFiles: readMatching(pkg.path, LICENSE_FILE),
      noticeFile: isApache(pkg.license) ? readMatching(pkg.path, NOTICE_FILE)[0] : undefined,
    }));
}

function fenced(text: string): string {
  const longest = Math.max(0, ...[...text.matchAll(/`+/g)].map((m) => m[0].length));
  const fence = '`'.repeat(Math.max(3, longest + 1));
  return `${fence}text\n${text}\n${fence}`;
}

/** Deterministic: sorted, no dates, no absolute paths. */
export function renderNotices(
  packages: readonly NoticePackage[],
  copied: readonly CopiedEntry[],
): string {
  const out: string[] = [
    '# Third-party notices',
    '',
    'This file is generated by `pnpm notices` (tools/verify). Do not edit it by hand: `pnpm verify` fails when it is out of date.',
    '',
    'OTheater itself is licensed under MPL-2.0 (see `LICENSE`). The software below is bundled with, or copied into, OTheater.',
    '',
    '## Bundled dependencies (level B)',
    '',
  ];
  const sorted = [...packages].sort(
    (a, b) => compareStrings(a.name, b.name) || compareStrings(a.version, b.version),
  );
  if (sorted.length === 0) {
    out.push('No third-party dependency is bundled yet.', '');
  }
  for (const pkg of sorted) {
    out.push(`### ${pkg.name}@${pkg.version}`, '', `- License: ${pkg.license}`);
    if (isMpl(pkg.license)) {
      out.push(
        `- Source code (MPL-2.0): ${pkg.repository ?? `not declared in the package; see the npm registry page of ${pkg.name}@${pkg.version}`}`,
      );
    }
    out.push('');
    if (pkg.licenseFiles.length === 0) {
      out.push(
        'No license file was found in the package; the license above is the one declared in its package.json.',
        '',
      );
    }
    for (const file of pkg.licenseFiles) {
      out.push(`License text (${file.fileName}):`, '', fenced(file.text), '');
    }
    if (pkg.noticeFile !== undefined) {
      out.push(`NOTICE (${pkg.noticeFile.fileName}):`, '', fenced(pkg.noticeFile.text), '');
    }
  }
  out.push('## Copied code (level A)', '');
  const entries = sortCopied(copied);
  if (entries.length === 0) {
    out.push('No third-party code has been copied into this repository yet.', '');
  }
  for (const entry of entries) {
    out.push(
      `### ${entry.project}`,
      '',
      `- License: ${entry.license}`,
      `- Origin: ${entry.sourcePath} at commit ${entry.commit}`,
      `- Local files: ${entry.localFiles.map((f) => `\`${f}\``).join(', ')}`,
      '',
      'Copyright notice:',
      '',
      fenced(normalizeText(entry.copyrightNotice)),
      '',
    );
  }
  return `${out.join('\n').trimEnd()}\n`;
}

/**
 * The platform the committed file is generated on. The bundled set includes the native binary
 * package of the platform that ran the install (`@napi-rs/keyring-linux-x64-gnu` here), so the
 * file rendered on Windows or macOS differs by design.
 */
export const NOTICES_PLATFORM: NodeJS.Platform = 'linux';

export function checkNotices(
  expected: string,
  onDisk: string | undefined,
  fileName: string,
  platform: NodeJS.Platform = NOTICES_PLATFORM,
): CheckResult {
  if (onDisk === undefined) {
    return {
      summary: [],
      findings: [
        {
          severity: 'error',
          subject: fileName,
          message: 'file does not exist; run "pnpm notices" to generate it',
        },
      ],
    };
  }
  if (onDisk !== expected && platform !== NOTICES_PLATFORM) {
    return {
      summary: [],
      findings: [
        {
          severity: 'warning',
          subject: fileName,
          message: `differs from the one rendered on ${platform}; it is generated on ${NOTICES_PLATFORM}, whose native packages are the bundled ones`,
        },
      ],
    };
  }
  if (onDisk !== expected) {
    return {
      summary: [],
      findings: [
        {
          severity: 'error',
          subject: fileName,
          message: 'out of date; run "pnpm notices" and commit the result',
        },
      ],
    };
  }
  return { summary: [`${fileName} is up to date`], findings: [] };
}
