/** Files of the repository a platform's notices carry whole (the Windows launcher's own list of crates). */
export const PLATFORM_EXTRAS: Readonly<
  Partial<Record<PlatformId, readonly { title: string; file: string }[]>>
> = {
  'win32-x64': [
    {
      title: 'Windows job launcher (native/job-launcher)',
      file: 'native/job-launcher/THIRD_PARTY_NOTICES.md',
    },
  ],
};

/** Build tools (level D, architecture 6.0): never in what is distributed, so never in the notices. */
export const BUILD_TOOL_PACKAGES: readonly RegExp[] = [/^esbuild$/, /^@esbuild\//, /^postject$/];

export function isBuildTool(name: string): boolean {
  return BUILD_TOOL_PACKAGES.some((pattern) => pattern.test(name));
}

const packageId = (pkg: { name: string; version: string }): string => `${pkg.name}@${pkg.version}`;

/** One package of the production graph of a platform. */
export interface PlatformEntry {
  name: string;
  version: string;
  /** The package on disk, when this machine has it. */
  installed: InstalledPackage | undefined;
  /** When it is not on disk: the installed package that declares it as an optional dependency. */
  parent: InstalledPackage | undefined;
  /** The native binary package of the platform: it travels as an asset, so the metafile does not list it. */
  native: boolean;
}

/**
 * The production dependency graph of `platform`, from the packages installed on this machine and the
 * lockfile. pnpm installs only the optional packages that fit the host, so the binary packages of the
 * other platforms (`@napi-rs/keyring-<platform>`) are not on disk: the ones that do not fit `platform`
 * are dropped, and the one that fits is found in the optional dependencies of the installed package
 * that declares it. `better-sqlite3` is no case of this: its binaries for every platform are inside
 * the one package.
 */
export function platformGraph(
  prod: readonly InstalledPackage[],
  lock: Lockfile,
  platform: PlatformId,
): PlatformEntry[] {
  const entries = new Map<string, PlatformEntry>();
  for (const pkg of prod) {
    const constraint = lock.constrained.get(packageId(pkg));
    if (constraint !== undefined && !constraintMatches(constraint, platform)) continue;
    entries.set(packageId(pkg), {
      name: pkg.name,
      version: pkg.version,
      installed: pkg,
      parent: undefined,
      native: constraint !== undefined,
    });
  }
  for (const parent of prod) {
    for (const [name, version] of lock.optionalDependencies.get(packageId(parent)) ?? []) {
      const id = `${name}@${version}`;
      const constraint = lock.constrained.get(id);
      if (constraint === undefined || !constraintMatches(constraint, platform)) continue;
      if (entries.has(id)) continue;
      entries.set(id, { name, version, installed: undefined, parent, native: true });
    }
  }
  return [...entries.values()].sort(
    (a, b) => compareStrings(a.name, b.name) || compareStrings(a.version, b.version),
  );
}

/** A version with major, minor and patch (and an optional prerelease and build). */
const WHOLE_SEMVER = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/;

/**
 * The packages an esbuild metafile says went into the bundle, as `name@version` (`name@*` when the
 * path has no version, which a layout other than pnpm's gives). The source of truth is the `inputs`
 * paths: `node_modules/.pnpm/<name>@<version>[_<peers>]/node_modules/<name>/...`.
 *
 * pnpm shortens a store folder whose name is longer than `virtual-store-dir-max-length` (by
 * default 60 on Windows and 120 elsewhere [S: pnpm docs]) to a prefix and a hash, which can cut the
 * version (`@agentclientprotocol+sdk@2._<hash>` on the Windows runner [V: CI log of 2026-11-22]).
 * A version that is not a whole semver is read as `name@*`: the name is still checked against the
 * graph, the version is not.
 */
export function bundledPackageIds(metafile: unknown): Set<string> {
  const inputs = isRecord(metafile) && isRecord(metafile.inputs) ? metafile.inputs : {};
  const ids = new Set<string>();
  for (const file of Object.keys(inputs)) {
    const posix = file.split('\\').join('/');
    const at = posix.lastIndexOf('node_modules/');
    if (at < 0) continue;
    const match = /^((?:@[^/]+\/)?[^/]+)\//.exec(posix.slice(at + 'node_modules/'.length));
    const name = match?.[1];
    if (name === undefined) continue;
    const store = /node_modules\/\.pnpm\/([^/]+)\/node_modules\//.exec(posix);
    const prefix = `${name.replace('/', '+')}@`;
    const dir = store?.[1];
    const version =
      dir?.startsWith(prefix) === true ? (dir.slice(prefix.length).split('_')[0] ?? '') : '';
    if (WHOLE_SEMVER.test(version)) {
      ids.add(`${name}@${version}`);
    } else {
      ids.add(`${name}@*`);
    }
  }
  return ids;
}

function isBundled(bundled: ReadonlySet<string>, pkg: { name: string; version: string }): boolean {
  return bundled.has(packageId(pkg)) || bundled.has(`${pkg.name}@*`);
}

/**
 * Crosses the graph with the bundle: what is listed is what was bundled plus the native addon of the
 * platform. `unknown` is what the bundle has and no production dependency explains (a development
 * dependency that got bundled would have no license decision behind it).
 */
export function selectBundled(
  entries: readonly PlatformEntry[],
  prod: readonly InstalledPackage[],
  bundled: ReadonlySet<string>,
): { selected: PlatformEntry[]; unknown: string[] } {
  const selected = entries.filter((entry) => entry.native || isBundled(bundled, entry));
  const known = new Set([...entries, ...prod].map(packageId));
  const knownNames = new Set([...entries, ...prod].map((pkg) => pkg.name));
  const unknown = [...bundled]
    .filter((id) => (id.endsWith('@*') ? !knownNames.has(id.slice(0, -2)) : !known.has(id)))
    .sort(compareStrings);
  return { selected, unknown };
}

/**
 * What the installed tree says the file of the machine's own platform must list: the production
 * packages that were bundled (all of them without a metafile) and the native ones. It does not go
 * through the platform graph, so it tells a lockfile reading that is wrong.
 */
export function installedSelection(
  prod: readonly InstalledPackage[],
  lock: Lockfile,
  bundled: ReadonlySet<string> | undefined,
): string[] {
  return prod
    .filter(
      (pkg) =>
        bundled === undefined || lock.constrained.has(packageId(pkg)) || isBundled(bundled, pkg),
    )
    .map(packageId);
}

/** LICENSE/NOTICE of every entry: from disk, or, for a package that is not here, from the one that declares it. */
export function gatherPlatformNotices(entries: readonly PlatformEntry[]): NoticePackage[] {
  return entries.map((entry) => {
    if (entry.installed !== undefined) return readNoticePackage(entry.installed);
    if (entry.parent === undefined)
      throw new Error(`${packageId(entry)} has neither a folder nor a parent`);
    return {
      ...readNoticePackage(entry.parent),
      name: entry.name,
      version: entry.version,
      derivedFrom: packageId(entry.parent),
    };
  });
}

/** Reads the extra sections of `platform` (files of the repository) from `root`. */
export function readExtraSections(root: string, platform: PlatformId): ExtraSection[] {
  return (PLATFORM_EXTRAS[platform] ?? []).map(({ title, file }) => ({
    title,
    text: readFileSync(path.join(root, file), 'utf8'),
  }));
}

/**
 * The lines of `text` that are not inside a fenced block, which is where the license texts live and
 * where a `### ` line is only text.
 */
function unfencedLines(text: string): string[] {
  const lines: string[] = [];
  let fence: string | undefined;
  for (const line of text.split('\n')) {
    if (fence === undefined) {
      const open = /^(`{3,})text$/.exec(line);
      if (open?.[1] !== undefined) fence = open[1];
      else lines.push(line);
    } else if (line === fence) {
      fence = undefined;
    }
  }
  return lines;
}

/** The `name@version` of every `### ` heading of the bundled-dependencies section of a notices file. */
export function listedPackageIds(text: string): string[] {
  const ids: string[] = [];
  let inBundled = false;
  for (const line of unfencedLines(text)) {
    if (line.startsWith('## ')) inBundled = line === BUNDLED_HEADING;
    else if (inBundled && line.startsWith('### ')) ids.push(line.slice(4).trim());
  }
  return ids;
}

export interface PlatformCheckInput {
  platform: PlatformId;
  /** `name@version` the graph (crossed with the bundle) says the file must list. */
  expectedIds: readonly string[];
  /** The file as written, `undefined` when it does not exist. */
  onDisk: string | undefined;
  fileName: string;
  /** Bundled packages no production dependency explains. */
  unknownBundled?: readonly string[] | undefined;
  /** On the platform of the machine: the packages the installed tree says (the graph is derived from the lockfile). */
  installedIds?: readonly string[] | undefined;
  /** On the platform of the machine: the file the generator would write now, to tell a stale file. */
  rendered?: string | undefined;
}

/** The file of a platform has the packages of its graph, no more and no less, and no build tool. */
export function checkPlatformNotices(input: PlatformCheckInput): CheckResult {
  const { platform, fileName } = input;
  const findings: CheckResult['findings'] = [];
  const error = (subject: string, message: string): void => {
    findings.push({ severity: 'error', subject, message });
  };
  for (const id of input.unknownBundled ?? []) {
    error(
      id,
      'is in the bundle but is not a production dependency (level B), so it has no license decision',
    );
  }
  if (input.installedIds !== undefined) {
    const expected = new Set(input.expectedIds);
    const installed = new Set(input.installedIds);
    for (const id of installed) {
      if (!expected.has(id))
        error(id, `is installed here but the graph of ${platform} (from the lockfile) lacks it`);
    }
    for (const id of expected) {
      if (!installed.has(id))
        error(id, `is in the graph of ${platform} (from the lockfile) but is not installed here`);
    }
  }
  if (input.onDisk === undefined) {
    error(fileName, 'file does not exist; generate it with "pnpm notices --platform"');
    return { summary: [], findings };
  }
  const expected = new Set(input.expectedIds);
  const listed = listedPackageIds(input.onDisk);
  const listedSet = new Set(listed);
  for (const id of [...expected].sort(compareStrings)) {
    if (!listedSet.has(id)) error(fileName, `package missing from the file: ${id}`);
  }
  for (const id of [...listedSet].sort(compareStrings)) {
    if (expected.has(id)) continue;
    const name = id.slice(0, id.lastIndexOf('@'));
    error(
      fileName,
      isBuildTool(name)
        ? `${id} is a build tool (level D) and must not be in the notices`
        : `package not in the graph of ${platform}: ${id}`,
    );
  }
  if (listed.length !== listedSet.size) error(fileName, 'a package is listed more than once');
  if (!input.onDisk.startsWith(`# Third-party notices (${platform})`)) {
    error(fileName, `the file does not say it is the one of ${platform}`);
  }
  const extras = PLATFORM_EXTRAS[platform] ?? [];
  const headings = new Set(unfencedLines(input.onDisk).filter((line) => line.startsWith('## ')));
  for (const extra of extras) {
    if (!headings.has(`## ${extra.title}`)) error(fileName, `section missing: ${extra.title}`);
  }
  for (const other of Object.values(PLATFORM_EXTRAS).flat()) {
    if (!extras.includes(other) && headings.has(`## ${other.title}`)) {
      error(fileName, `section of another platform: ${other.title}`);
    }
  }
  if (findings.length === 0 && input.rendered !== undefined && input.onDisk !== input.rendered) {
    error(fileName, 'out of date; generate it again with "pnpm notices --platform"');
  }
  return {
    summary:
      findings.length === 0
        ? [`${fileName} lists the ${String(expected.size)} package(s) of the ${platform} graph`]
        : [],
    findings,
  };
}
